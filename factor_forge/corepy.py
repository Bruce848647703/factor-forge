def factor_to_company_spec(fac: Factor, runner_name: str) -> Dict:
    """Factor -> the spec.json schema used by signal-library repos."""
    formula_lines = [ln for ln in (fac.formula or "").splitlines() if ln.strip()]
    var_desc = "；".join(
        f"{v.symbol}: {v.description or v.name_cn}" for v in fac.variables)
    return {
        "signal_name": runner_name,
        "signal_name_raw": fac.name_cn,
        "signal_category": fac.category,
        "signal_formula_raw": " \\quad ".join(formula_lines),
        "signal_formula": formula_lines,
        "signal_variables_name": [v.symbol for v in fac.variables],
        "signal_formula_add": "",
        "signal_variables_name_add": [],
        "signal_variables_description": var_desc,
        "signal_description": fac.description,
        "signal_reference": fac.source,
        "human_feedback": "",
    }


