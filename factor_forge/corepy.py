# canonical fields each operator consumes (shared with datadict binding)
_OP_FIELDS = OPERATOR_FIELDS


def _needed_fields(fac: Factor) -> List[str]:
    """Ordered union of operator-implied fields and declared variable fields."""
    op = fac.operator or "generic"
    seen, out = set(), []
    for f in (_OP_FIELDS.get(op) or []) + fac.required_fields():
        if f and f not in seen:
            seen.add(f)
            out.append(f)
    return out

# default params + history length (read_tradingdays count) per operator
_OP_DEFAULTS = {
    "turnover_weighted_price": ({"lookback": 120}, lambda p: p["lookback"] + 1),
    "momentum": ({"lag": 12, "skip": 1}, lambda p: p["lag"] + 1),
    "reversal": ({"period": 1}, lambda p: p["period"] + 1),
    "volatility": ({"window": 20}, lambda p: p["window"] + 2),
    "generic": ({}, lambda p: 60),
}


def _params(fac: Factor) -> Dict:
    defaults, _ = _OP_DEFAULTS.get(fac.operator or "generic", ({}, None))
    defaults = dict(defaults)
    defaults.update(fac.params or {})
    return defaults


def _varmap_block(fac: Factor, bindings: Dict[str, DictBinding]) -> str:
    if not fac.variables:
        return "  (no variables declared)"
    rows = []
    for v in fac.variables:
        b = bindings.get(v.data_field)
        if not v.data_field:
            where = "(parameter)"
        elif b is None:
            if v.data_field in UNBOUND_FIELDS:
                where = "(fundamental field - bind before production)"
            else:
                where = "(UNBOUND - TODO, see datadict.example.com)"
        elif b.expr:
            where = f"{b.table}: {b.expr}"
        else:
            where = f"{b.table}.{b.column}"
        rows.append(f"  {v.symbol:<10} {v.name_cn:<8} -> {where}")
    return "\n".join(rows)


def _select_block(fac: Factor, bindings: Dict[str, DictBinding]) -> str:
    """SQL select list: InnerID/DataDate + one line per bound field."""
    lines = ["            InnerID,", "            DataDate,"]
    op = fac.operator or "generic"
    for field_name in _needed_fields(fac):
        b = bindings.get(field_name)
        if b is None:
            lines.append(f"            -- TODO: bind '{field_name}' "
                         f"via datadict.example.com")
            continue
        lines.append(f"            {b.select_expr},")
    return "\n".join(lines).rstrip(",\n")


def generate_corepy(fac: Factor, runner_id: int = 0,
                    runner_name: Optional[str] = None,
                    bindings: Optional[Dict[str, DictBinding]] = None) -> str:
    """Generate the company-format core.py for a Factor."""
    if bindings is None:
        bindings = {k: BUILTIN_BINDINGS[k]
                    for k in _needed_fields(fac) if k in BUILTIN_BINDINGS}
    op = fac.operator or "generic"
    params = _params(fac)
    _, hist_fn = _OP_DEFAULTS.get(op, ({}, lambda p: 60))

    name = runner_name or fac.name
    if not name.startswith("Signal_"):
        name = f"Signal_{name}"

    header = _CORE_HEADER.format(
        runner_name=name, name_cn=fac.name_cn or "-",
        category=fac.category or "-", operator=op,
        direction={1: "+1", -1: "-1", 0: "0"}.get(fac.direction, "?"),
        direction_note=fac.direction_note or "", source=fac.source or "-",
        formula=fac.formula or "(none)",
        varmap=_varmap_block(fac, bindings), runner_id=runner_id)

    const_lines = []
    if op == "turnover_weighted_price":
        const_lines.append(f"LOOKBACK: Final = {int(params['lookback'])}")
    elif op == "momentum":
        const_lines.append(f"LAG: Final = {int(params['lag'])}")
        const_lines.append(f"SKIP: Final = {int(params['skip'])}")
    elif op == "reversal":
        const_lines.append(f"PERIOD: Final = {int(params['period'])}")
    elif op == "volatility":
        const_lines.append(f"WINDOW: Final = {int(params['window'])}")
    consts = ("\n".join(const_lines) + "\n") if const_lines else ""

    read_daily = _READ_DAILY.format(select_list=_select_block(fac, bindings),
                                    table=TABLE_QUALIFIED)

    calc_tmpl = _OP_CALC.get(op)
    if calc_tmpl is not None:
        calc = calc_tmpl
    else:
        formula_indented = "\n    # ".join((fac.formula or "").splitlines())
        cols = []
        for f in _needed_fields(fac):
            b = bindings.get(f)
            cols.append(f if b is None else b.data_field)
        calc = _CALC_GENERIC.format(formula_indented=formula_indented,
                                    fields=", ".join(cols) or "n/a")

    body = header + consts + read_daily + calc + _BUILD_SIGNAL + \
        _GET_SIGNAL.format(hist_days=hist_fn(params))
    # build_signal_data uses duckdb; keep the import with the top block
    body = body.replace("import numpy as np\nimport pandas as pd\n",
                        "import duckdb\nimport numpy as np\n"
                        "import pandas as pd\n", 1)
    return body


